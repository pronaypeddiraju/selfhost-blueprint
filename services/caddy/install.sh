#!/usr/bin/env bash
# install.sh — Caddy reverse proxy. Renders the Caddyfile for the services you
# actually have running, using the TLS mode you chose in .env.
#
#   TLS_MODE=none      plain HTTP on :80. No Vaultwarden (it needs a secure context).
#   TLS_MODE=internal  Caddy's own local CA -> https://<svc>.home.arpa on your LAN.
#                      Requires installing Caddy's root cert on client devices.
#   TLS_MODE=dns01     Wildcard public cert via Cloudflare DNS-01. Needs APP_DOMAIN
#                      + CLOUDFLARE_API_TOKEN. No inbound ports; works off-LAN.
#
# Safe to re-run at any time — it regenerates the Caddyfile from what exists.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$SCRIPT_DIR/lib/common.sh"; source "$SCRIPT_DIR/lib/detect.sh"
load_env; require_docker

TLS_MODE="${TLS_MODE:-internal}"
case "$TLS_MODE" in
  none|internal|dns01) ;;
  *) die "TLS_MODE must be one of: none | internal | dns01 (got '$TLS_MODE')" ;;
esac

if [ "$TLS_MODE" = "dns01" ]; then
  require_var APP_DOMAIN
  require_var CLOUDFLARE_API_TOKEN
  BASE_DOMAIN="$APP_DOMAIN"
else
  # RFC 8375 reserves .home.arpa for home networks — no public DNS involvement.
  BASE_DOMAIN="${BASE_DOMAIN:-home.arpa}"
fi

# Hostname label : container name : port env var : default port
TABLE="
adguard:adguard:ADGUARD_HTTP_PORT:3000
vaultwarden:vaultwarden:VAULTWARDEN_HTTP_PORT:8000
uptimekuma:uptimekuma:UPTIMEKUMA_HTTP_PORT:3001
homepage:homepage:HOMEPAGE_HTTP_PORT:3002
scrutiny:scrutiny:SCRUTINY_HTTP_PORT:8081
immich:immich_server:IMMICH_HTTP_PORT:2283
jellyfin:jellyfin:JELLYFIN_HTTP_PORT:8096
mealie:mealie:MEALIE_HTTP_PORT:9925
silverbullet:silverbullet:SILVERBULLET_HTTP_PORT:3030
filebrowser:filebrowser:FILEBROWSER_HTTP_PORT:8082
seerr:seerr:SEERR_PORT:5055
qbittorrent:qbittorrent:QBIT_HTTP_PORT:8080
radarr:radarr:RADARR_PORT:7878
sonarr:sonarr:SONARR_PORT:8989
prowlarr:prowlarr:PROWLARR_PORT:9696
bazarr:bazarr:BAZARR_PORT:6767
"

# ---------------------------------------------------------------------------
# Render. Only services whose container actually exists get a site block, so a
# half-installed stack doesn't produce a Caddyfile full of 502s.
# ---------------------------------------------------------------------------
CFG_DIR="$SCRIPT_DIR/services/caddy/config"
mkdir -p "$CFG_DIR"
CFG="$CFG_DIR/Caddyfile"
RUNNING="$(docker ps -a --format '{{.Names}}' 2>/dev/null || true)"
EMITTED=0

{
  printf '# Generated by services/caddy/install.sh — TLS_MODE=%s, BASE_DOMAIN=%s\n' "$TLS_MODE" "$BASE_DOMAIN"
  printf '# Re-run ./install.sh --services=caddy after adding or removing services.\n\n'
  # Global options. Setting the TLS policy globally (not per-site) is what makes
  # Caddy provision a certificate for EVERY site block; a per-site snippet
  # silently only covered the first one.
  printf '{\n'
  case "$TLS_MODE" in
    dns01)    printf '  acme_dns cloudflare {env.CLOUDFLARE_API_TOKEN}\n' ;;
    internal) printf '  local_certs\n' ;;
    none)     printf '  auto_https off\n' ;;
  esac
  printf '}\n\n'

  for row in $TABLE; do
    IFS=: read -r name container var def <<< "$row"
    printf '%s\n' "$RUNNING" | grep -qx "${DOCKER_PREFIX:-}${container}" || continue

    port="${!var:-}"; port="${port:-$def}"
    host="$name.$BASE_DOMAIN"
    printf '%s {\n  reverse_proxy %s:%s\n}\n\n' "$host" "${HOST_IP:-127.0.0.1}" "$port"
    EMITTED=$((EMITTED + 1))
  done

  if [ "$EMITTED" -eq 0 ]; then
    printf '# No running services detected yet — install some, then re-run\n# ./install.sh --services=caddy to regenerate this file.\n'
  fi
} > "$CFG"

log_info "Rendered $CFG ($EMITTED site block(s), mode=$TLS_MODE, domain=$BASE_DOMAIN)"
[ "$EMITTED" -gt 0 ] && require_var HOST_IP

docker compose -f "$SCRIPT_DIR/services/caddy/compose.yaml" up -d >/dev/null 2>&1

# The image runs `caddy run` WITHOUT --watch, so a regenerated Caddyfile is not
# picked up until we reload it. Skipping this leaves new site blocks invisible.
if docker exec "${DOCKER_PREFIX:-}caddy" caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1; then
  log_info "Caddy reloaded with the new config."
else
  log_warn "Caddy reload failed — restarting the container instead."
  docker restart "${DOCKER_PREFIX:-}caddy" >/dev/null 2>&1 || true
fi

log_ok "Caddy running."
case "$TLS_MODE" in
  internal) log_info "Add a DNS rewrite '*.${BASE_DOMAIN} -> ${HOST_IP:-this host}' and install Caddy's root cert per device — docs/19-tls.md" ;;
  dns01)    log_info "Point *.${BASE_DOMAIN} at ${HOST_IP:-this host} in your DNS provider — docs/05-reverse-proxy.md" ;;
  none)     log_warn "TLS_MODE=none: Vaultwarden will NOT work until you switch to internal or dns01." ;;
esac